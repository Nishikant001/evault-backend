// src/models/tenantModels/BiometricDevice.js
//
// One row = one phone that a user has enabled "fingerprint login" on.
// NOTHING biometric is stored here (no fingerprint, no template). The row
// only holds a SHA-256 hash of a random device secret that lives in the
// phone's secure keystore, protected by the OS biometric prompt.
const { DataTypes } = require("sequelize");

module.exports = (sequelize) => sequelize.define(
  "BiometricDevice",
  {
    id: { type: DataTypes.INTEGER, primaryKey: true, autoIncrement: true },

    // Owner. Tenant isolation comes from this table living in the tenant's own DB.
    userId: { type: DataTypes.INTEGER, allowNull: false },

    // Public identifier (UUID) generated by the server at enrollment.
    deviceId: { type: DataTypes.STRING(64), allowNull: false, unique: true },

    // SHA-256 hex of the secret part of the device token. Raw secret is never stored.
    secretHash: { type: DataTypes.STRING(64), allowNull: false },

    deviceLabel: { type: DataTypes.STRING(120), allowNull: true }, // e.g. "Pixel 7 (android)"
    platform: { type: DataTypes.STRING(20), allowNull: true },

    lastUsedAt: { type: DataTypes.DATE, allowNull: true },
    expiresAt: { type: DataTypes.DATE, allowNull: false },

    // Revocation: non-null revokedAt = device can no longer log in.
    revokedAt: { type: DataTypes.DATE, allowNull: true },
    revokedReason: { type: DataTypes.STRING(60), allowNull: true },
  },
  {
    tableName: "biometric_devices",
    timestamps: true,
    indexes: [{ fields: ["userId"] }],
  },
);
